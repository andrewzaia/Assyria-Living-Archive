"""Searchable, linked ancient text concordance with explicit source relationship roles."""
from html import escape as H
from concordance import TERMS


def _list_items(items, fn, empty=None):
    if not items:
        return '<p class="concordance-empty">' + H(empty or "No link is asserted in this category.") + '</p>'
    return '<ul class="concordance-evidence-list">' + ''.join(fn(item) for item in items) + '</ul>'


def _object(item):
    kind = "Edited line" if item.get("line") else "Object-level record"
    label = item["title"] + (" / " + item["line"] if item.get("line") else "")
    return ('<li><a href="' + H(item["url"], quote=True) + '">' + H(label) + '</a>'
            '<span class="concordance-role">' + H(kind) + '</span>'
            '<p>' + H(item["note"]) + '</p>'
            '<small>Edition: ' + H(item["edition"]) + ' / '
            '<a href="' + H(item["source_url"], quote=True) +
            '" target="_blank" rel="noopener noreferrer">Source publication</a></small></li>')


def _article(item):
    return '<li><a href="' + H(item["url"], quote=True) + '">' + H(item["title"]) + '</a></li>'


def _passage(item):
    return ('<li><a href="' + H(item["url"], quote=True) + '">' + H(item["label"]) + '</a>'
            '<span class="concordance-role">Biblical text / different source genre</span><p>' +
            H(item["note"]) + '</p></li>')


def render(heading, view, report):
    cards = []
    for term in view:
        search = " ".join([term["label"], term["description"], *term["aliases"], term["type"]]).casefold()
        alias_text = ", ".join(term["aliases"])
        cards.append(
            '<li class="concordance-term" id="entry-' + H(term["id"]) +
            '" data-type="' + H(term["type"]) + '" data-search="' + H(search, quote=True) + '">' +
            '<div class="concordance-term-heading"><span class="eyebrow">' + H(term["type"].replace("-", " ")) +
            '</span><h3>' + H(term["label"]) + '</h3>' +
            ('<p class="concordance-aliases">Also indexed as: ' + H(alias_text) + '</p>' if alias_text else '') +
            '<p>' + H(term["description"]) + '</p></div>' +
            '<div class="concordance-links"><section aria-label="Attested tablet or object references"><h4>Object and line references (' +
            str(len(term["objects"])) + ')</h4>' +
            _list_items(term["objects"], _object, "No physical-object link is asserted.") +
            '</section><section aria-label="Related encyclopaedia studies"><h4>Research chapters (' +
            str(len(term["articles"])) + ')</h4>' +
            _list_items(term["articles"], _article, "No additional research chapter linked.") +
            '</section><section aria-label="Biblical comparison passages"><h4>Biblical reading (' +
            str(len(term["passages"])) + ')</h4>' +
            _list_items(term["passages"], _passage, "No biblical correspondence is claimed.") +
            '</section></div></li>'
        )
    return (
        '<main id="main" class="wrap section concordance-room">' +
        heading("RESEARCH / SOURCE CONCORDANCE", "Trace a term to its evidence.",
                "A curated cross-reference of ancient places, people, materials and documentary language, with separate source roles.") +
        '<div class="concordance-intro"><p><strong>Search the connection, not an invented equivalence.</strong> '
        'A tablet line is an edited inscription reference; an object-level link is catalogue context; '
        'a Bible reading is primary for what Scripture states. The index does not merge people or campaigns just because similar words appear.</p>'
        '<p>Every case-level link opens the original object study, with direct line anchors where a cited excerpt is present. '
        'Published editions and biblical passages remain accessible. The relationships are selected by editors rather than generated by unrestricted keyword matching. '
        'Review the <a href="/identity-register/">name and identity register</a> before equating similar names.</p></div>' +
        '<section class="concordance-browser" aria-labelledby="concordance-browser-title">' +
        '<div class="concordance-header"><span class="eyebrow">CURATED EVIDENCE CONNECTIONS</span>' +
        '<h2 id="concordance-browser-title">Browse the terms.</h2><p>' + str(report["terms"]) + ' terms / ' +
        str(report["object_links"]) + ' cited object relationships / ' + str(report["passage_links"]) +
        ' biblical comparison routes</p></div>' +
        '<div class="concordance-controls" role="search">' +
        '<div><label for="concordance-query">Search names, objects and terms</label>' +
        '<input id="concordance-query" type="search" autocomplete="off" placeholder="Try barley, Nineveh or damaged signs"></div>' +
        '<div><label for="concordance-type">Category</label><select id="concordance-type">' +
        '<option value="">All categories</option>' +
        ''.join('<option value="' + H(v) + '">' + H(v.replace("-", " ").title()) + '</option>'
                for v in ("place", "person", "material", "institution", "practice", "textual-method")) +
        '</select></div></div>' +
        '<p id="concordance-count" class="concordance-count" role="status" aria-live="polite">' +
        'Showing all ' + str(len(cards)) + ' curated terms.</p>' +
        '<ol class="concordance-term-list">' + ''.join(cards) + '</ol>' +
        '<p id="concordance-no-results" hidden>No matching curated term. Try another phrase or category.</p>' +
        '</section><section class="concordance-method" aria-labelledby="concordance-method-title">' +
        '<h2 id="concordance-method-title">A reading route, not a completed review.</h2>' +
        '<p>These relationships do not verify Akkadian sign restorations, prove shared ancient identities or claim that a biblical report and an Assyrian object document the identical event. The existing ' +
        '<a href="/text-comparisons/">text comparison collection</a> and ' +
        '<a href="/case-files/">object dossiers</a> show precisely where edited lines are available or still missing. ' +
        'Visit the <a href="/about/evidence/">Evidence Register</a> for the claim-review queue and ' +
        '<a href="/governance/">editorial review limitations</a>.</p></section></main>'
    )
